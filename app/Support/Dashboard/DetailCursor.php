<?php

namespace App\Support\Dashboard;

use DateTimeImmutable;
use DateTimeZone;
use Illuminate\Pagination\Cursor;

final class DetailCursor
{
    public static function issue(?Cursor $cursor, string $scope): ?string
    {
        if ($cursor === null) {
            return null;
        }

        $encoded = $cursor->encode();

        return $encoded.'.'.self::signature($encoded, $scope);
    }

    public static function accept(mixed $token, string $column, string $asOf, string $scope): string
    {
        if (! is_string($token) || strlen($token) > 192
            || ! preg_match('/\A([A-Za-z0-9_-]+)\.([a-f0-9]{64})\z/', $token, $parts)
            || ! hash_equals(self::signature($parts[1], $scope), $parts[2])) {
            return '';
        }

        $parameters = Cursor::fromEncoded($parts[1])?->toArray();
        $time = $parameters[$column] ?? null;
        $id = $parameters['id'] ?? null;
        $direction = $parameters['_pointsToNextItems'] ?? null;

        if (! is_string($time) || ! preg_match('/\A[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2}\z/', $time)
            || $time > $asOf || ! is_int($id) || $id < 1 || ! is_bool($direction)) {
            return '';
        }

        $parsed = DateTimeImmutable::createFromFormat('!Y-m-d H:i:s', $time, new DateTimeZone('UTC'));
        if ($parsed === false || $parsed->format('Y-m-d H:i:s') !== $time) {
            return '';
        }

        // Require the exact shape and canonical encoding generated by Laravel.
        return (new Cursor([$column => $time, 'id' => $id], $direction))->encode() === $parts[1] ? $parts[1] : '';
    }

    private static function signature(string $encoded, string $scope): string
    {
        return hash_hmac('sha256', "sitepulse:monitor-detail|$scope|$encoded", app('encrypter')->getKey());
    }
}
